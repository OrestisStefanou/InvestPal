evaluate_investment_theme_skill = """
## CORE LOGIC

### Purpose

A theme is a story about the future that implies a set of investments. Themes
are how most retail capital is allocated and how most of it is lost. The job of
this skill is to convert a narrative into a falsifiable claim, derive the
candidate set from the structure of the industry rather than from recall, and
work out who actually captures the economics.

### Why Themes Destroy More Capital Than They Create

Themes are usually **right about the world and wrong about the investment**. The
internet did transform commerce; almost every 1999 internet stock was still a
catastrophe. Being correct about the trend is the easy part and is not
compensated, because the trend is already consensus by the time it has a name.

Three structural reasons a correct theme still loses money:

1. **The theme is priced.** If you can name it, the multiple already reflects it.
2. **Growth without profit.** A theme raises industry volume. It says nothing
   about whether anyone earns a return above cost of capital on that volume.
   Competition often converts the entire benefit into consumer surplus.
3. **The purest expression is the worst risk.** The pure-play carries a scarcity
   premium and has no other business to fall back on when timing is wrong.

The correct posture is: treat the theme as a screen for where to look, never as
a reason to own.

---

## STEP 0: STATE THE THEME AS A FALSIFIABLE CLAIM

Force the theme into this form before doing anything else:

> **X will happen by Y, and I will know it is happening because Z.**

* **X** is a specific, physical or economic change, not a mood
* **Y** is a horizon, because a theme with no horizon can never be wrong
* **Z** is an observable series that would move first

A theme with no named falsifier is a narrative, not a thesis. Say so and stop.

Bad: "AI is going to be huge."
Better: "Data centre power demand will grow faster than utility supply through
2030, observable in interconnection queue lengths and industrial power pricing."

The second version tells you what to buy, when you are wrong, and what to watch.
The first tells you nothing.

Also record what is **already consensus**. The tradeable part of a theme is the
gap between what is priced and what will happen, never the theme itself.

---

## THEME VALIDATION

### 1. DRIVER TEST

What forces the change? Distinguish:

* **Structural drivers**: regulation, demographics, physics, cost curves that
  only move one way, installed-base replacement cycles. These are durable.
* **Cyclical drivers**: capacity shortage, a price spike, post-shock restocking,
  a subsidy with an expiry date. These mean-revert and are frequently sold as
  secular.

The most common analytical error in thematic investing is a cyclical driver
dressed as a structural one. If the theme depends on a price staying high, it is
cyclical. High prices cure high prices.

### 2. DURABILITY AND TIMING

* How long does the change take to play out, and does that match the horizon?
* What is the adoption curve position: pre-inflection, steep, or saturating?
* What could stop it: substitution, regulation, a physical bottleneck, a
  cheaper alternative?

Timing risk is not a footnote. A theme that is right five years early is
indistinguishable from wrong for anyone with a finite holding period.

### 3. SIZE OF PRIZE VERSUS SIZE OF PRICE

Estimate the total profit pool the theme creates at maturity, then compare it
against the aggregate market capitalisation already attributed to it. When the
combined value of the theme's participants already exceeds any plausible
mature-state profit pool discounted back, the theme is fully priced no matter
how real it is.

---

## FROM THEME TO CANDIDATE SET

This is the core mechanic. Candidates are **derived by walking the value chain**,
never recalled from a list. A derived set is auditable, covers positions a list
would miss, and forces you to state why each name belongs.

### Value-Chain Mapping

Decompose the theme into six positions:

1. **Scarce inputs** -- raw materials, specialised components, land, spectrum,
   power, permits. Whoever holds the binding constraint captures the rent.
2. **Core producers** -- the companies that make the thing the theme is about.
   Usually the most crowded and least attractive position.
3. **Enablers** -- tools, equipment, testing, software, and services that every
   producer needs regardless of which producer wins. The pick-and-shovel trade.
4. **Distribution and integration** -- whoever controls access to the end
   customer, installation, or the standard.
5. **Downstream beneficiaries** -- companies whose costs fall or whose addressable
   market grows because the theme succeeded. Often the cheapest exposure and
   almost always the least discussed.
6. **Disrupted losers** -- who is structurally worse off. These are avoid or
   short candidates, and identifying them tests whether the theme is real.

A theme where you cannot populate a scarce-input or enabler position is usually
a theme with no defensible way to invest in it.

### Expanding the Chain into Names

For each position, work outward from what you can establish rather than guessing:

1. Identify one or two anchor companies you can name with confidence for that
   position
2. Take the anchor's sector and industry classification and expand to its peer
   set
3. Read each candidate's revenue segmentation to score how much of the business
   is actually exposed to the theme
4. Discard any name you cannot tie to a specific chain position

### Purity Versus Quality

Score every candidate on two independent axes:

* **Theme purity**: high (most of revenue), partial (a meaningful segment), or
  incidental (a rounding error)
* **Business quality**: returns on capital, competitive position, balance sheet,
  independent of the theme

These are usually inversely correlated. The purest names are typically the
youngest, least profitable, and most expensive. The highest-quality exposure is
usually partial. Say explicitly which trade-off the candidate represents.

---

## WHO CAPTURES THE ECONOMICS

A theme raises volume. It does not distribute profit. Profit accrues to whoever
holds a bottleneck: a scarce input, a switching cost, a standard, a network, or
a cost advantage.

The test: **is the theme showing up in the candidate's margins, or only in its
revenue?** Revenue growth with flat or falling margins means the company is
passing the entire benefit to customers. It is a participant, not a beneficiary.

Ask for each candidate:
* What stops a competitor from doing this?
* Who is the marginal supplier, and what happens to price when capacity arrives?
* Is this company a price setter or a price taker?

In a commoditised link of the chain, the correct number of investments is zero,
however real the theme.

---

## PRICED-IN CHECK

* How has the candidate's valuation moved since the theme acquired its name?
* Is the current multiple above or below its own history, and by how much?
* What growth rate is implied by the current price, and is it achievable?
* How much of the shareholder register is thematic or index-driven flow rather
  than fundamental?

The last point matters more than it appears. Crowding through thematic funds
creates correlated forced selling: when the theme falls out of favour, every
name in it is sold together regardless of individual merit.

---

## THEME FAILURE MODES

Check the candidate set against each:

1. **Right theme, wrong stock** -- the theme works, this company does not capture it
2. **Right theme, too early** -- correct at a horizon longer than you can hold
3. **Competed away** -- volume grows, economic profit does not
4. **Cyclical in secular clothing** -- the driver mean-reverts
5. **Pure-play premium** -- the cleanest expression carries the worst risk-adjusted price
6. **Crowding** -- thematic fund flows dominate the register and reverse together
7. **The segment is immaterial** -- the theme is real for the company but is 3% of revenue
8. **Second-order substitution** -- the theme succeeds via a technology other than the one you own

---

## POSITION CONSTRUCTION

If the theme survives, treat the exposure as a basket rather than a single name,
because single-name risk within a correct theme is the dominant failure mode.
Weight toward quality and partial purity rather than the purest expression. Size
against the timing risk, not the conviction in the theme. Define in advance the
observation that would falsify the thesis and the multiple at which the theme
becomes fully priced regardless of outcome.

---

## OUTPUT FORMAT

Present candidates as a table:

| Name | Chain position | Theme purity | Business quality | Valuation vs own history | Verdict |
| --- | --- | --- | --- | --- | --- |

Every row must name its chain position. A candidate with no chain position does
not belong in the table.

---

## ANALYST VERDICT

Must include:

1. **The falsifiable claim**: the theme restated as X by Y observable via Z
2. **Driver classification**: structural or cyclical, with reasoning
3. **Where the economics accrue**: which chain position captures the profit, and why
4. **Priced-in assessment**: how much of the theme is already in the price
5. **Candidate table**: derived names with chain position and purity
6. **The falsifier**: what observation would end the thesis
7. **Explicit caveat**: that this list is derived, not curated, and that no name is
   actionable until it has been through valuation and margin-of-safety analysis

---

## STYLE RULES

* Never present the derived list as a recommendation -- it is a research agenda
* Never include a name you cannot tie to a specific chain position
* Always state each candidate's theme purity, and never let purity substitute for quality
* Always state the theme's falsifier -- a thesis that cannot be wrong is not a thesis
* Flag explicitly when the purest expression of the theme is also the lowest quality
* Distinguish "the theme is real" from "the theme is investable" in every conclusion
* Never estimate a company's revenue exposure to a theme without saying what the
  estimate rests on
* If no chain position has defensible economics, say the theme is not investable
  and recommend nothing
"""
